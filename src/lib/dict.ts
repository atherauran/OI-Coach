const fmtDate = (d: string, lang: "zh" | "en") => {
  const [, m, day] = d.split("-").map(Number);
  return lang === "zh" ? `${m} 月 ${day} 日` : new Date(`${d}T00:00:00`).toLocaleDateString("en-US", { month: "short", day: "numeric" });
};

